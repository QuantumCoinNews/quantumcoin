def runtime_data_path(path):
    return bool(re.search(r"\.(db|sqlite|sqlite3)(?:$|[-.])",path,re.I)) or bool(
        re.search(r"(^|/)admin_settlement_report[^/]*$",path,re.I))


def source_exclusion(path):
    """Identify local runtime, generated artifacts, raw diagnostics and secret paths."""
    lower = path.lower().replace("\\", "/")
    if lower.startswith("telegram_game/telegram_game/dev_ui/assets/qc_wallet_crypto/"):
        return True  # Generated by build_wallet_crypto.py from the pinned Go toolchain.
    parts = lower.split("/")
    name = parts[-1]
    if name in {".vscode", "id_ed25519_quantumcoin_release"}:
        return True
    if name.startswith((".qc-wallet-", ".qc-encrypted-backup-")):
        return True  # Incomplete wallet writes can contain custody material.
    if name.endswith((".bak", ".disabled")) or ".before_" in name:
        return True
    if parts[0] == ".vscode" and lower not in {".vscode/settings.json", ".vscode/launch.json"}:
        return True
    if (lower == "config.json" or name in LOCAL_STATE_FILES or lower in MACHINE_SNAPSHOTS or name == "desktop.ini" or
            lower.startswith(LOCAL_OUTPUT_PREFIXES) or
            any(part in GENERATED_DIRECTORIES or part.endswith((".security", ".monitoring", ".advisory"))
                for part in parts[:-1]) or name.startswith((".security-event-", ".ai-record-", ".monitoring-"))):
        return True
    if lower in {"autopublisher/last.json", "autopublisher/autopublisher.lock",
                  "autopublisher/assets/bg.mp4", "autopublisher/src/content/pool/pool_state.json"}:
        return True
    if lower.startswith("autopublisher/") and (name.endswith((".local", ".dpapi.json")) or name.startswith(".tmp-")):
        return True
    if ".before-" in name or lower == "assets/user closing conversation.html" or lower.startswith(
        ("assets/user closing conversation_files/", "i18n/bin/")
    ):
        return True
    if runtime_data_path(lower):
        return True
    if any(part in {"node_modules", "__pycache__", "__qcdiag", "_local_audit_reports",
                    "_local_audit_backups", "_wm_review", "old_working_release", "_checkpoints"}
           or part.startswith(("_legacy_runtime_", "release_backup_", "release_clean_test"))
           for part in parts[:-1]):
        return True
    if parts[0] in {"bin", "build"} or lower.startswith(
        ("cmd/wallet/build/", "webwallet/dist/", "release/dist/", "autopublisher/out/", "autopublisher/tmp/")
    ):
        return True
    if any(part in {"secrets", ".wallet", ".venv", "venv"} for part in parts[:-1]):
        return True
    if name != ".env.example" and (name.endswith(".env") or name.startswith(".env.")):
        return True
    if name in {".wallet", ".chain.json", ".quantumcoin-network.json", "wallet_address.txt", "miner_address.txt",
                "private.key", "private.json", "secrets.json", "token.json",
                "go_env.txt", "tree.txt", "build_errors.txt", "block_around_141.txt", "symbols.txt"}:
        return True
    if lower not in PUBLIC_SECURITY_SOURCES and re.search(r"(?:wallet.*priv|miner.*priv|private[_-]?key|wallet_recovery|credentials|client_secret|oauth.*token)", name):
        return True
    if re.match(r"^(?:chain_data|security_events|wallet_data|wallet_balance|bonus_store)(?:[_.-]|$)", name):
        return True
    return bool(re.search(r"\.(exe|dll|pdb|so|dylib|dat|log|zip|7z|rar|tar|gz|pem|key|pfx|p12|qcwallet|qcvault|qcbak|pyc)$", name)
                or re.search(r"\.(dat|log)[.-]", name))


def git_paths(repo,ref=None):
    command=["git","ls-tree","-r","--name-only","-z",ref] if ref else ["git","ls-files","-z"]
    data=subprocess.run(command,cwd=repo,check=True,capture_output=True).stdout
    return [name.decode("utf-8",errors="strict") for name in data.split(b"\x00") if name]


def working_source_inventory(repo):
    """Canonical working-tree membership; never include local config or custody."""
    raw = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
                         cwd=repo, check=True, capture_output=True).stdout
    paths = set(raw.decode("utf-8").strip("\0").split("\0"))
    for directory in ("telegram_game/telegram_game/dev_ui/assets", "webui/dist"):
        base = repo / directory
        if base.is_dir():
            paths.update(path.relative_to(repo).as_posix() for path in base.rglob("*") if path.is_file())
    result = []
    for name in sorted(paths):
        if not name or name == "config.json" or source_exclusion(name):
            continue
        path = repo / name
        if not path.is_file():
            continue
        if path.resolve() != path:
            raise ValueError("indirect source path requires review")
        result.append(name)
    return {"sourcePaths": result}


def check(repo):
    index=sorted(p for p in git_paths(repo) if runtime_data_path(p))
    committed=sorted(p for p in git_paths(repo,"HEAD") if runtime_data_path(p))
    return {"ok":not(index or committed),"trackedRuntimePaths":index,"committedRuntimePaths":committed}


def check_source(repo, ref="HEAD"):
    index = sorted(p for p in git_paths(repo) if source_exclusion(p))
    committed = sorted(p for p in git_paths(repo, ref) if source_exclusion(p))
    return {"ok": not (index or committed), "trackedExcludedPaths": index,
            "committedExcludedPaths": committed}


def cleanup_class(path):
    if path.lower().replace("\\", "/") in PUBLIC_SECURITY_SOURCES:
        return None
    parts = path.lower().split("/")
    name = parts[-1]
    if name == "id_ed25519_quantumcoin_release":
        return "secret"
    if name == ".vscode":
        return "archive"
    if name.startswith((".qc-wallet-", ".qc-encrypted-backup-")):
        return "secret"
    # A pruned legacy directory can contain both artifacts and wallet/chain
    # custody. Its summary must never authorize deletion as build output.
    if name == "__layout_probe__" and (
            parts[0] in {"bin", "build"} or path.startswith("release/dist/") or
            any(part.startswith("release_clean_test") for part in parts[:-1])):
        return "mixed-custody-review"
    if path.startswith(("_local_audit_reports/", "_local_audit_backups/", "__qcdiag/", "i18n/bin/")):
        return "archive"
    if path.startswith("telegram_game/telegram_game/dev_ui/assets/qc_wallet_crypto/"):
        return "generated"
    if parts[0] == ".vscode" and path not in {".vscode/settings.json", ".vscode/launch.json"}:
        return "runtime"
    if path.lower() == "config.json" or name in LOCAL_STATE_FILES:
        return "runtime"
    if path.lower() in MACHINE_SNAPSHOTS:
        return "archive"
    if path.lower().startswith(("release/_testnet_backups/", "release/_pre_testnet_checkpoints/")):
        return "archive"
    if path.lower().startswith(("offline-recovery/", "_backups/")):
        return "archive"
    if path.lower().startswith(("autopublisher/state/", "autopublisher/media/", "autopublisher/assets/pool/")):
        return "runtime"
    if path.lower().startswith("autopublisher/") and name.endswith((".local", ".dpapi.json")):
        return "secret"
    if any(part in GENERATED_DIRECTORIES for part in parts[:-1]) or name == "desktop.ini":
        return "generated"
    if path.lower().startswith(LOCAL_OUTPUT_PREFIXES):
        return "generated"
    if any(part.endswith((".security", ".monitoring", ".advisory")) for part in parts[:-1]):
        return "runtime"
    if (name != ".env.example" and (name.endswith(".env") or name.startswith(".env."))) or any(
        part in {"secrets", ".wallet"} for part in parts
    ) or re.search(r"wallet.*priv|miner.*priv|private[_-]?key|wallet_recovery|credentials|client_secret|oauth.*token|\.(pem|key|pfx|p12|qcwallet|qcvault|qcbak)$", name):
        return "secret"
    if (runtime_data_path(path) or name == ".chain.json" or
            re.match(r"^(chain_data|security_events|wallet_data|wallet_balance|bonus_store)(?:[_.-]|$)", name) or
            name in {"wallet_address.txt", "miner_address.txt"} or re.search(r"\.(dat|log)(?:$|[.-])", name)):
        return "runtime"
    if (".before-" in name or name.endswith((".bak", ".disabled", ".zip", ".7z", ".rar", ".tar", ".gz")) or
            any(part.startswith(("_legacy_runtime_", "_wm_review", "_checkpoints", "release_backup_", "old_working_release"))
                for part in parts[:-1])):
        return "archive"
    if (name.endswith((".exe", ".dll", ".pdb", ".so", ".dylib", ".pyc")) or
            any(part in {"node_modules", "__pycache__"} for part in parts[:-1]) or
            path.startswith(("autopublisher/out/", "autopublisher/tmp/", "webwallet/dist/", "cmd/wallet/build/"))):
        return "generated"
    if source_exclusion(path):
        return "manual-review"
    if parts[0] == "release":
        return "release-source-review"
    return None


def cleanup_plan(repo):
    index = set(git_paths(repo))
    head = set(git_paths(repo, "HEAD"))
    records = []
    for path in sorted(index | head):
        kind = cleanup_class(path)
        if kind:
            records.append({"path": path, "class": kind, "inIndex": path in index,
                            "inHead": path in head, "present": (repo / path).exists()})
    return {
        "ok": True, "mode": "read-only", "scope": "index-and-HEAD", "records": records,
        "beforeRemoval": {
            "mixed-custody-review": "Inventory descendants and verify wallet/chain custody before any relocation or deletion",
            "secret": "Review custody and exposure independently before any source removal",
            "runtime": "Verify owner, network identity, retention and recovery",
            "archive": "Verify canonical equivalent, call graph and retention",
            "generated": "Verify build provenance and replacement artifact",
            "manual-review": "Verify owner and runtime references",
            "release-source-review": "Verify release manifest and build inputs",
        },
    }


def layout_inventory(repo):
    """Inspect paths and metadata, never open runtime/credential file contents."""
    repo = repo.resolve()
    records = []
    for directory, children, files in os.walk(repo, followlinks=False):
        parent = Path(directory)
        retained = []
        for name in sorted(children):
            if name == ".git":
                continue
            path = parent / name
            relative = path.relative_to(repo).as_posix()
            probe = relative + "/__layout_probe__"
            if path.is_symlink() or path.resolve() != path:
                records.append({"path": relative, "kind": "directory", "role": "indirect-review"})
            elif source_exclusion(probe):
                if relative == ".vscode":
                    retained.append(name)  # Public settings/launch remain source.
                    continue
                records.append({"path": relative, "kind": "directory",
                                "role": cleanup_class(probe) or "manual-review"})
            else:
                retained.append(name)
        children[:] = retained
        for name in sorted(files):
            path = parent / name
            relative = path.relative_to(repo).as_posix()
            if not source_exclusion(relative):
                continue
            if path.is_symlink() or path.resolve() != path:
                records.append({"path": relative, "kind": "file", "role": "indirect-review"})
                continue
            info = path.stat()
            records.append({"path": relative, "kind": "file", "bytes": info.st_size,
                            "role": cleanup_class(relative) or "manual-review"})
    gate = check_source(repo)
    return {"ok": True, "mode": "metadata-only", "runtimeContentsRead": False,
            "sourcePaths": working_source_inventory(repo)["sourcePaths"],
            "excludedWorkingPaths": sorted(records, key=lambda row: row["path"]),
            "excludedRoleCounts": dict(sorted(Counter(row["role"] for row in records).items())),
            "sourceGate": gate,
            "scope": "directory records represent pruned subtrees, not individual file totals"}


def archive(repo,destination):
    ref = subprocess.run(["git", "rev-parse", "--verify", "HEAD^{commit}"], cwd=repo,
                         check=True, capture_output=True, text=True).stdout.strip()
    result=check_source(repo, ref)
    if not result["ok"]:
        raise ValueError("Local runtime, secret or generated files are tracked; refuse source archive")
    target=Path(destination).resolve()
    with target.open("xb") as stream:
        process=subprocess.run(["git","archive","--format=zip","--prefix=quantumcoin/",ref],cwd=repo,stdout=stream,stderr=subprocess.PIPE)
    if process.returncode:
        target.unlink()  # Only the new file created with exclusive 'xb' above.
        raise ValueError("Source archive failed")
    return {"ok":True,"archive":str(target),"ref":ref,"includesWorkingTreeEdits":False}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo",type=Path,default=Path(__file__).resolve().parents[1])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--archive",type=Path)
    mode.add_argument("--cleanup-plan", action="store_true")
    mode.add_argument("--inventory", action="store_true")
    mode.add_argument("--layout", action="store_true", help="metadata-only source/runtime placement inventory")
    args=parser.parse_args()
    if args.inventory:
        print(json.dumps(working_source_inventory(args.repo.resolve()), indent=2))
        return 0
    if args.cleanup_plan:
        result = cleanup_plan(args.repo)
    elif args.layout:
        result = layout_inventory(args.repo)
    elif args.archive:
        result = archive(args.repo,args.archive)
    else:
        result = check_source(args.repo)
    print(json.dumps(result,indent=2))
    return 0 if result["ok"] else 1


if __name__=="__main__":raise SystemExit(main())
